import { TELEPHONY_PROVIDERS } from '@pv/shared';
import { prisma } from '../lib/prisma';
import { logger } from '../lib/logger';
import { forbidden, notFound } from '../lib/http-error';
import { verifySubject } from '../lib/signed-url';
import { applyCallStatus, isTerminal } from '../services/calls';
import { canStartCall } from '../services/entitlements';
import { adapterForAccount, type TelephonyAdapter, type VoiceDocument } from './index';
import { callbackFields } from './webhook-fields';
import { legStreamUrl, mediaStreamUrl } from './stream-urls';
import { transferLegs } from '../voice/transfer-bridge';
import { assertCarrierSignature } from './carrier-signature';

export { inboundStreamUrl, legStreamUrl, mediaStreamUrl } from './stream-urls';

/**
 * Carrier webhooks. Every URL was generated by signedCallbackUrl(), so each
 * handler first checks `sig` against the call or number id it names.
 *
 *   POST /:provider/inbound?numberId=…  someone called a connected number
 *   POST /:provider/inbound?accountId=… the same, for carriers that route a
 *        whole account/application to one URL (Telnyx, Vonage, Bandwidth):
 *        the number is found by the number dialled
 *   POST /:provider/voice?callId=…      our outbound call was answered
 *   POST /:provider/status?callId|numberId|accountId=…  progress and hangup
 *   POST /:provider/leg-voice?callId=…  the person a call is being transferred to answered
 *   POST /:provider/leg-status?callId=… progress of that call (voice/transfer-bridge.ts)
 */
export const telephonyWebhooksRouter = Router();

/** How far back an outbound call makes an incoming one a call-back. */
const CALLBACK_WINDOW_MS = 30 * 24 * 60 * 60 * 1000;

const UNAVAILABLE =
  'Sorry, no one is available to take your call right now. Please try again later. Goodbye.';
/** Said to a team member who picks up a transfer after the caller has gone. */
const TRANSFER_GONE = 'Sorry, the caller has already hung up. Goodbye.';

function provider(param: string): TelephonyProvider {
  const p = param.toUpperCase() as TelephonyProvider;
  if (!(TELEPHONY_PROVIDERS as readonly string[]).includes(p)) throw notFound('Provider');
  return p;
}

const body = (req: Request) => (req.body ?? {}) as Record<string, unknown>;

function send(res: Response, doc: VoiceDocument) {
  res.type(doc.contentType).send(doc.body);
}

function e164(raw: unknown): string {
  const s = String(raw ?? '').trim();
  return s.startsWith('+') ? s : `+${s.replace(/\D/g, '')}`;
}

type InboundNumber = PhoneNumber & {
  telephonyAccount: TelephonyAccount;
  inboundAgent: Agent | null;
};

/**
 * Creates the Call for someone calling a connected number, or returns null
 * when no agent can take it (the caller is told so and hung up on).
 *
 * Someone an agent called from this number calling back gets that agent,
 * with its call-back instructions and what happened last time. Anyone else
 * gets the agent the number is assigned to.
 */
export async function openInboundCall(
  number: InboundNumber,
  from: string,
  providerCallId: string | null,
) {
  const prior = await prisma.call.findFirst({
    where: {
      phoneNumberId: number.id,
      direction: 'OUTBOUND',
      toNumber: from,
      agentId: { not: null },
      createdAt: { gte: new Date(Date.now() - CALLBACK_WINDOW_MS) },
    },
    orderBy: { createdAt: 'desc' },
    select: { contactId: true, agent: true },
  });
  const callbackAgent = prior?.agent?.status === 'ACTIVE' ? prior.agent : null;
  const agent = callbackAgent ?? number.inboundAgent;
  if (!agent || agent.status !== 'ACTIVE') return null;
  const gate = await canStartCall(number.workspaceId);
  if (!gate.ok) {
    logger.info({ numberId: number.id, reason: gate.reason }, 'Inbound call refused');
    return null;
  }

  const now = new Date();
  return prisma.call.create({
    data: {
      workspaceId: number.workspaceId,
      agentId: agent.id,
      phoneNumberId: number.id,
      provider: number.telephonyAccount.provider,
      providerCallId,
      direction: 'INBOUND',
      fromNumber: from,
      toNumber: number.e164,
      isCallback: !!callbackAgent,
      // Gives the agent the contact's name and CSV fields; with no campaign
      // set, the call-back doesn't change that campaign's progress.
      contactId: callbackAgent ? prior!.contactId : null,
      status: 'IN_PROGRESS',
      startedAt: now,
      answeredAt: now,
    },
  });
}

/** The number an inbound webhook is about: by its id, or by the number dialled on an account. */
async function inboundNumber(req: Request, p: TelephonyProvider) {
  const include = { telephonyAccount: true, inboundAgent: true } as const;
  const numberId = typeof req.query.numberId === 'string' ? req.query.numberId : null;
  if (numberId) {
    if (!verifySubject('inbound', numberId, req.query.sig)) throw forbidden('Bad signature');
    const number = await prisma.phoneNumber.findUnique({ where: { id: numberId }, include });
    if (!number || number.telephonyAccount.provider !== p) throw notFound('Number');
    return { number, account: number.telephonyAccount };
  }
  const accountId = String(req.query.accountId ?? '');
  if (!verifySubject('inbound', accountId, req.query.sig)) throw forbidden('Bad signature');
  const account = await prisma.telephonyAccount.findUnique({ where: { id: accountId } });
  if (!account || account.provider !== p) throw notFound('Account');
  const to = callbackFields(p, body(req)).to;
  const number = to
    ? await prisma.phoneNumber.findFirst({
        where: { telephonyAccountId: account.id, e164: e164(to) },
        include,
      })
    : null;
  return { number, account };
}

telephonyWebhooksRouter.post('/:provider/inbound', async (req, res) => {
  const p = provider(req.params.provider);
  const { number, account } = await inboundNumber(req, p);
  assertCarrierSignature(req, account);
  const adapter = adapterForAccount(account);
  // A number on the carrier account that isn't connected to Purple Voice.
  if (!number) return send(res, adapter.sayAndHangupDocument(UNAVAILABLE));
  const fields = callbackFields(p, body(req));
  const call = await openInboundCall(number, e164(fields.from), fields.providerCallId ?? null);
  if (!call) return send(res, adapter.sayAndHangupDocument(UNAVAILABLE));
  send(res, adapter.streamDocument(mediaStreamUrl(p, call.id)));
});

telephonyWebhooksRouter.post('/:provider/voice', async (req, res) => {
  const p = provider(req.params.provider);
  const callId = String(req.query.callId ?? '');
  if (!verifySubject('voice', callId, req.query.sig)) throw forbidden('Bad signature');

  const call = await prisma.call.findUnique({
    where: { id: callId },
    include: { phoneNumber: { include: { telephonyAccount: true } } },
  });
  if (!call?.phoneNumber || call.provider !== p) throw notFound('Call');
  assertCarrierSignature(req, call.phoneNumber.telephonyAccount);
  const adapter: TelephonyAdapter = adapterForAccount(call.phoneNumber.telephonyAccount);
  if (isTerminal(call.status)) return send(res, adapter.sayAndHangupDocument('Goodbye.'));

  // Plivo's call id only exists once the call is answered; until now we held its request id.
  await applyCallStatus(call.id, 'IN_PROGRESS', {
    providerCallId: p === 'PLIVO' ? callbackFields(p, body(req)).providerCallId : undefined,
  });
  send(res, adapter.streamDocument(mediaStreamUrl(p, call.id)));
});

telephonyWebhooksRouter.post('/:provider/status', async (req, res) => {
  const p = provider(req.params.provider);
  const fields = callbackFields(p, body(req));
  let callId = typeof req.query.callId === 'string' ? req.query.callId : null;

  if (callId) {
    if (!verifySubject('status', callId, req.query.sig)) throw forbidden('Bad signature');
    const call = await prisma.call.findUnique({
      where: { id: callId },
      select: {
        provider: true,
        providerCallId: true,
        phoneNumber: { select: { telephonyAccount: true } },
      },
    });
    if (!call || call.provider !== p) throw notFound('Call');
    if (call.phoneNumber) assertCarrierSignature(req, call.phoneNumber.telephonyAccount);
    // Vonage reports every leg of a call to its event URL; only the call's own leg counts.
    if (
      p === 'VONAGE' &&
      call.providerCallId &&
      fields.providerCallId &&
      fields.providerCallId !== call.providerCallId
    )
      callId = null;
  } else {
    // Inbound calls report status against the number's (or the account's) callback URL.
    const numberId = typeof req.query.numberId === 'string' ? req.query.numberId : null;
    const subject = numberId ?? String(req.query.accountId ?? '');
    if (!verifySubject('status', subject, req.query.sig)) throw forbidden('Bad signature');
    const account = numberId
      ? (
          await prisma.phoneNumber.findUnique({
            where: { id: numberId },
            select: { telephonyAccount: true },
          })
        )?.telephonyAccount
      : await prisma.telephonyAccount.findUnique({ where: { id: subject } });
    if (!account || account.provider !== p) throw notFound('Number');
    assertCarrierSignature(req, account);
    const call = fields.providerCallId
      ? await prisma.call.findFirst({
          where: {
            provider: p,
            providerCallId: fields.providerCallId,
            ...(numberId
              ? { phoneNumberId: numberId }
              : { phoneNumber: { telephonyAccountId: account.id } }),
          },
        })
      : null;
    callId = call?.id ?? null;
  }

  if (callId && fields.status) {
    await applyCallStatus(callId, fields.status, { durationSec: fields.durationSec });
  }
  res.status(204).end();
});

/** The person an AI call is being transferred to picked up. */
telephonyWebhooksRouter.post('/:provider/leg-voice', async (req, res) => {
  const p = provider(req.params.provider);
  const callId = String(req.query.callId ?? '');
  if (!verifySubject('leg-voice', callId, req.query.sig)) throw forbidden('Bad signature');
  const call = await prisma.call.findUnique({
    where: { id: callId },
    include: { phoneNumber: { include: { telephonyAccount: true } } },
  });
  if (!call?.phoneNumber || call.provider !== p) throw notFound('Call');
  assertCarrierSignature(req, call.phoneNumber.telephonyAccount);
  const adapter = adapterForAccount(call.phoneNumber.telephonyAccount);
  const leg = transferLegs.get(callId);
  if (!leg?.answered(callbackFields(p, body(req)).providerCallId)) {
    return send(res, adapter.sayAndHangupDocument(TRANSFER_GONE));
  }
  send(res, adapter.streamDocument(legStreamUrl(p, callId), leg.intro));
});

/** Progress of the call to that person: busy, no answer, hung up. */
telephonyWebhooksRouter.post('/:provider/leg-status', async (req, res) => {
  const p = provider(req.params.provider);
  const callId = String(req.query.callId ?? '');
  if (!verifySubject('leg-status', callId, req.query.sig)) throw forbidden('Bad signature');
  const { status } = callbackFields(p, body(req));
  if (status) transferLegs.get(callId)?.status(status);
  res.status(204).end();
});
