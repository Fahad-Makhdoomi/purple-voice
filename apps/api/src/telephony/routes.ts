import { Router, type Response } from 'express';
import type { TelephonyProvider } from '@prisma/client';
import { publicWsUrl } from '../config/env';
import { prisma } from '../lib/prisma';
import { logger } from '../lib/logger';
import { forbidden, notFound } from '../lib/http-error';
import { signSubject, verifySubject } from '../lib/signed-url';
import { applyCallStatus, isTerminal } from '../services/calls';
import { canStartCall } from '../services/entitlements';
import { adapterForAccount, type TelephonyAdapter, type VoiceDocument } from './index';
import { TWILIO_STATUS } from './twilio';
import { PLIVO_STATUS } from './plivo';

/**
 * Carrier webhooks. Every URL was generated by signedCallbackUrl(), so each
 * handler first checks `sig` against the call or number id it names.
 *
 *   POST /:provider/inbound?numberId=…  someone called a connected number
 *   POST /:provider/voice?callId=…      our outbound call was answered
 *   POST /:provider/status?callId|numberId=…  progress and hangup
 *   POST /:provider/transfer?callId=…   transfer document (Plivo fetches it)
 */
export const telephonyWebhooksRouter = Router();

const UNAVAILABLE =
  'Sorry, no one is available to take your call right now. Please try again later. Goodbye.';

function provider(param: string): TelephonyProvider {
  const p = param.toUpperCase();
  if (p !== 'TWILIO' && p !== 'PLIVO' && p !== 'SUPERPHONE') throw notFound('Provider');
  return p;
}

function send(res: Response, doc: VoiceDocument) {
  res.type(doc.contentType).send(doc.body);
}

function e164(raw: unknown): string {
  const s = String(raw ?? '').trim();
  return s.startsWith('+') ? s : `+${s.replace(/\D/g, '')}`;
}

/** Media stream URL. Signature in the path because Twilio drops query strings on stream URLs. */
export function mediaStreamUrl(p: TelephonyProvider, callId: string): string {
  return publicWsUrl(`/ws/${p.toLowerCase()}/${callId}/${signSubject('media', callId)}`);
}

function mapStatus(p: TelephonyProvider, body: Record<string, string>) {
  const raw = String(body.CallStatus ?? '').toLowerCase();
  return p === 'PLIVO' ? PLIVO_STATUS[raw] : TWILIO_STATUS[raw];
}

telephonyWebhooksRouter.post('/:provider/inbound', async (req, res) => {
  const p = provider(req.params.provider);
  const numberId = String(req.query.numberId ?? '');
  if (!verifySubject('inbound', numberId, req.query.sig)) throw forbidden('Bad signature');

  const number = await prisma.phoneNumber.findUnique({
    where: { id: numberId },
    include: { telephonyAccount: true, inboundAgent: true },
  });
  if (!number) throw notFound('Number');
  const adapter = adapterForAccount(number.telephonyAccount);
  const body = req.body as Record<string, string>;

  const agent = number.inboundAgent;
  if (!agent || agent.status !== 'ACTIVE')
    return send(res, adapter.sayAndHangupDocument(UNAVAILABLE));
  const gate = await canStartCall(number.workspaceId);
  if (!gate.ok) {
    logger.info({ numberId, reason: gate.reason }, 'Inbound call refused');
    return send(res, adapter.sayAndHangupDocument(UNAVAILABLE));
  }

  const now = new Date();
  const call = await prisma.call.create({
    data: {
      workspaceId: number.workspaceId,
      agentId: agent.id,
      phoneNumberId: number.id,
      provider: p,
      providerCallId: body.CallSid ?? body.CallUUID ?? null,
      direction: 'INBOUND',
      fromNumber: e164(body.From),
      toNumber: number.e164,
      status: 'IN_PROGRESS',
      startedAt: now,
      answeredAt: now,
    },
  });
  send(res, adapter.streamDocument(mediaStreamUrl(p, call.id)));
});

telephonyWebhooksRouter.post('/:provider/voice', async (req, res) => {
  const p = provider(req.params.provider);
  const callId = String(req.query.callId ?? '');
  if (!verifySubject('voice', callId, req.query.sig)) throw forbidden('Bad signature');

  const call = await prisma.call.findUnique({
    where: { id: callId },
    include: { phoneNumber: { include: { telephonyAccount: true } } },
  });
  if (!call?.phoneNumber) throw notFound('Call');
  const adapter: TelephonyAdapter = adapterForAccount(call.phoneNumber.telephonyAccount);
  if (isTerminal(call.status)) return send(res, adapter.sayAndHangupDocument('Goodbye.'));

  const body = req.body as Record<string, string>;
  // Plivo's call id only exists once the call is answered; until now we held its request id.
  await applyCallStatus(call.id, 'IN_PROGRESS', {
    providerCallId: p === 'PLIVO' ? body.CallUUID : undefined,
  });
  send(res, adapter.streamDocument(mediaStreamUrl(p, call.id)));
});

telephonyWebhooksRouter.post('/:provider/status', async (req, res) => {
  const p = provider(req.params.provider);
  const body = req.body as Record<string, string>;
  let callId = typeof req.query.callId === 'string' ? req.query.callId : null;

  if (callId) {
    if (!verifySubject('status', callId, req.query.sig)) throw forbidden('Bad signature');
  } else {
    // Inbound calls report status against the number's callback URL.
    const numberId = String(req.query.numberId ?? '');
    if (!verifySubject('status', numberId, req.query.sig)) throw forbidden('Bad signature');
    const providerCallId = body.CallSid ?? body.CallUUID;
    const call = providerCallId
      ? await prisma.call.findFirst({
          where: { provider: p, providerCallId, phoneNumberId: numberId },
        })
      : null;
    callId = call?.id ?? null;
  }

  const status = mapStatus(p, body);
  if (callId && status) {
    const duration = Number(body.CallDuration ?? body.Duration ?? NaN);
    await applyCallStatus(callId, status, {
      durationSec: Number.isFinite(duration) ? duration : undefined,
    });
  }
  res.status(204).end();
});

telephonyWebhooksRouter.post('/:provider/transfer', async (req, res) => {
  provider(req.params.provider);
  const callId = String(req.query.callId ?? '');
  if (!verifySubject('transfer', callId, req.query.sig)) throw forbidden('Bad signature');
  const call = await prisma.call.findUnique({
    where: { id: callId },
    include: { phoneNumber: { include: { telephonyAccount: true } } },
  });
  if (!call?.phoneNumber || !call.transferredTo) throw notFound('Transfer');
  const adapter = adapterForAccount(call.phoneNumber.telephonyAccount);
  send(res, adapter.transferDocument(call.transferredTo, call.phoneNumber.e164));
});
